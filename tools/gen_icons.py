"""Regenerates src/icons_data.inc from a lucide-static package.

Usage: tools/gen_icons.py <path to lucide-static/icons> > src/icons_data.inc

Only the SVG body (the shapes inside <svg>) is stored; the toolkit wraps it
with the header at render time, so color, stroke and caps can change.
"""
